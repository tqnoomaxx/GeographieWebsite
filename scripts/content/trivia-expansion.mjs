function card(continent, id, difficulty, question, labels, explanation, provenance) {
  return {
    id: `trivia:${id}`,
    type: 'trivia',
    names: { de: question },
    attributes: {
      choices: labels.map((label) => ({ id: slugify(label), label })),
      answer: slugify(labels[0]),
      explanation,
      difficulty,
      ...(continent ? { continent } : {}),
    },
    provenance: { ...provenance, last_updated: '2026-10-29', imported_at: '2026-10-29' },
  }
}
