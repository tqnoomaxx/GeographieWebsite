import type { PlayStationId } from '@/features/play/stationProgress'

type TaskBase = {
  id: string
  prompt: string
  hint: string
  explanation: string
  required?: boolean
  flag?: string
  sample?: { text: string; lang: string; dir?: 'rtl' | 'ltr' }
}
export type StoryTask = TaskBase &
  (
    | { mode: 'choice'; choices: string[]; answer: string }
    | { mode: 'input'; answer: string; accepted?: string[]; strict?: boolean }
    | { mode: 'order'; answer: string[]; instruction: string }
    | { mode: 'map'; answer: string; countries: string[] }
    | {
        mode: 'features'
        answer: string
        features: string[]
        featureType: 'river' | 'mountain'
        scope: string
      }
  )
export type StoryLevel = {
  id: string
  station: PlayStationId
  place: string
  title: string
  biome: string
  accent: string
  description: string
  dialogue: string
  goal: string
  artifact: string
  artifactDescription: string
  ending: string
  difficulty: number
  rank: string
  taskCount: number
  hintLimit: number
  mechanics: string
  position: { x: number; y: number }
  tasks: StoryTask[]
}
const choice = (
  id: string,
  prompt: string,
  answer: string,
  wrong: string[],
  hint: string,
  explanation: string,
  extra: Partial<TaskBase> = {},
): StoryTask => ({
  id,
  mode: 'choice',
  prompt,
  answer,
  choices: [answer, ...wrong],
  hint,
  explanation,
  ...extra,
})
const input = (
  id: string,
  prompt: string,
  answer: string,
  hint: string,
  explanation: string,
  extra: Partial<TaskBase> & { accepted?: string[]; strict?: boolean } = {},
): StoryTask => ({ id, mode: 'input', prompt, answer, hint, explanation, ...extra })
const order = (
  id: string,
  prompt: string,
  instruction: string,
  answer: string[],
  hint: string,
  explanation: string,
): StoryTask => ({ id, mode: 'order', prompt, instruction, answer, hint, explanation, required: true })
const map = (
  id: string,
  prompt: string,
  answer: string,
  countries: string[],
  hint: string,
  explanation: string,
): StoryTask => ({ id, mode: 'map', prompt, answer, countries, hint, explanation, required: true })
const river = (id: string, prompt: string, answer: string, hint: string, explanation: string): StoryTask => ({
  id,
  mode: 'features',
  prompt,
  answer,
  features: ['river:Q3392', 'river:Q3783', 'river:Q5089', 'river:Q1653'],
  featureType: 'river',
  scope: 'world',
  hint,
  explanation,
  required: true,
})
const summit = (
  id: string,
  prompt: string,
  answer: string,
  hint: string,
  explanation: string,
): StoryTask => ({
  id,
  mode: 'features',
  prompt,
  answer,
  features: ['mountain:Q513', 'mountain:Q43512', 'mountain:Q82019', 'mountain:Q165440'],
  featureType: 'mountain',
  scope: 'asia',
  hint,
  explanation,
  required: true,
})

